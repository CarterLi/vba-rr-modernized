// recursive kludge
static void InitMenuKludge(CMenu *pParentMenu, CMenu *pMenu, CCmdTarget *pWnd)
{
	ASSERT(pMenu != NULL);

	CCmdUI state;
	state.m_pParentMenu = pParentMenu;
	state.m_pMenu		= pMenu;
	ASSERT(state.m_pOther == NULL);

	state.m_nIndexMax = pMenu->GetMenuItemCount();
	for (state.m_nIndex = 0; state.m_nIndex < state.m_nIndexMax;
	     state.m_nIndex++)
	{
		state.m_nID = pMenu->GetMenuItemID(state.m_nIndex);
		if (state.m_nID == 0)
			continue;  // menu separator or invalid cmd - ignore it

		ASSERT(state.m_pOther == NULL);
		ASSERT(state.m_pMenu != NULL);
		if (state.m_nID == (UINT)-1)
		{
			// possibly a popup menu, route to first item of that popup
			state.m_pSubMenu = pMenu->GetSubMenu(state.m_nIndex);
			if (state.m_pSubMenu == NULL)
			{
				continue; // first item of popup can't be routed to
			}

			state.DoUpdate(pWnd, false);
			if (recursiveCall)
			{
				// FIXME: slow recursive calls to fix enabling/disabling of accel keys
				InitMenuKludge(state.m_pMenu, state.m_pSubMenu, pWnd);
			}
		}
		else
		{
			// normal menu item
			// Auto enable/disable if frame window has 'm_bAutoMenuEnable'
			//    set and command is _not_ a system command.
			state.m_pSubMenu = NULL;
			state.DoUpdate(pWnd, state.m_nID < 0xF000);
		}

		// adjust for menu deletions and additions
		UINT nCount = pMenu->GetMenuItemCount();
		if (nCount < state.m_nIndexMax)
		{
			state.m_nIndex -= (state.m_nIndexMax - nCount);
			while (state.m_nIndex < nCount &&
			       pMenu->GetMenuItemID(state.m_nIndex) == state.m_nID)
			{
				state.m_nIndex++;
			}
		}
		state.m_nIndexMax = nCount;
	}
}

// Rebuilds a "Screenshot Format" popup from the formats WIC can actually write
// (see ImageWrite.h).  Recognises the popup by the id range of its items, so it
// also does the initial fill that replaces the placeholder the resources carry.
// Returns true when the popup was one of ours.
static bool winUpdateCaptureFormatMenu(CMenu *pMenu)
{
	int count = pMenu->GetMenuItemCount();

	bool ours = false;
	for (int i = 0; i < count; ++i)
	{
		const UINT id = pMenu->GetMenuItemID(i);
		if (id >= ID_OPTIONS_EMULATOR_FORMAT_FIRST && id <= ID_OPTIONS_EMULATOR_FORMAT_LAST)
		{
			ours = true;
			break;
		}
	}

	if (!ours)
		return false;

	ImageWriteFormatInfo formats[16];
	const int            formatCount = imageWriteFormats(formats, 16);
	const int            current     = imageCaptureFormatIndex();

	while (pMenu->GetMenuItemCount() > 0)
		pMenu->DeleteMenu(0, MF_BYPOSITION);

	if (formatCount == 0)
	{
		pMenu->AppendMenu(MF_STRING | MF_GRAYED, ID_OPTIONS_EMULATOR_FORMAT_FIRST,
		                  imageWriteAvailable() ? _T("Unavailable") : _T("Not available on this Windows"));
		return true;
	}

	for (int i = 0; i < formatCount; ++i)
	{
		CString label = formats[i].name;
		label.Replace(_T(" Encoder"), _T(""));
		label.Trim();

		pMenu->AppendMenu(MF_STRING | (i == current ? MF_CHECKED : 0),
		                  ID_OPTIONS_EMULATOR_FORMAT_FIRST + i,
		                  label);
	}

	return true;
}

void MainWnd::OnInitMenuPopup(CMenu *pMenu, UINT nIndex, BOOL bSysMenu)
{
	ASSERT(pMenu != NULL);

	CCmdUI state;
	state.m_pMenu = pMenu;
	ASSERT(state.m_pOther == NULL);
	ASSERT(state.m_pParentMenu == NULL);

	// determine if menu is popup in top-level menu and set m_pOther to
	//  it if so (m_pParentMenu == NULL indicates that it is secondary popup)
	HMENU hParentMenu;
	if (AfxGetThreadState()->m_hTrackingMenu == pMenu->m_hMenu)
		state.m_pParentMenu = pMenu;  // parent == child for tracking popup
	else if ((hParentMenu = ::GetMenu(m_hWnd)) != NULL)
	{
		CWnd *pParent = GetTopLevelParent();
		// children windows don't have menus -- need to go to the top!
		if (pParent != NULL &&
		    (hParentMenu = ::GetMenu(pParent->m_hWnd)) != NULL)
		{
			int nIndexMax = ::GetMenuItemCount(hParentMenu);
			for (int nIndex = 0; nIndex < nIndexMax; nIndex++)
			{
				if (::GetSubMenu(hParentMenu, nIndex) == pMenu->m_hMenu)
				{
					// when popup is found, m_pParentMenu is containing menu
					state.m_pParentMenu = CMenu::FromHandle(hParentMenu);
					break;
				}
			}
		}
	}

	// FIXME: magic to workaround the accel key bug without slowing down too much
	if (translatingAccelerator && !fullUpdated && state.m_pParentMenu == &theApp.m_menu)
	{
		state.m_pMenu = state.m_pParentMenu;
		recursiveCall = true;
		fullUpdated	  = true;
	}
	else if (!translatingAccelerator && fullUpdated)
	{
		fullUpdated = false;
	}

	InitMenuKludge(state.m_pParentMenu, state.m_pMenu, this);

	recursiveCall = false;

	// Fill the screenshot format popup after the command UI pass so the checks
	// put on its items survive.
	winUpdateCaptureFormatMenu(pMenu);
}

