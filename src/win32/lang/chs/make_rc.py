def load_glossary():
    table = {}
    duplicates = []
    for name in sorted(os.listdir(HERE)):
        if not name.endswith(".tsv"):
            continue
        path = os.path.join(HERE, name)
        with open(path, encoding="utf-8-sig") as handle:
            for number, line in enumerate(handle, 1):
                line = line.rstrip("\n").rstrip("\r")
                if not line.strip() or line.lstrip().startswith("#"):
                    continue
                parts = line.split("\t")
                if len(parts) != 2:
                    sys.exit("%s:%d: expected two tab separated columns" % (name, number))
                source, translated = parts
                if source in table and table[source] != translated:
                    duplicates.append((source, table[source], translated, name))
                    continue
                table[source] = translated
    for source, first, second, name in duplicates:
        sys.exit("%s: %r is translated twice, as %r and %r"
                 % (name, source, first, second))
    return table


def read_blocks():
    with open(SOURCE, encoding="utf-8-sig") as handle:
        lines = handle.read().splitlines()

    blocks = []
    index = 0
    while index < len(lines):
        line = lines[index]
        if not line.lstrip().startswith("//") and BLOCK_START.match(line):
            block = [line]
            index += 1
            while index < len(lines):
                block.append(lines[index])
                # Only the END in column 0 closes a block; the ones that close
                # a nested POPUP are indented.
                done = lines[index].rstrip() == "END"
                index += 1
                if done:
                    break
            blocks.append(block)
        else:
            index += 1
    return blocks


def source_version():
    """The value both the executable and a language module carry.

    The raw bytes matter: the resource scripts are stored exactly as they are
    (see .gitattributes), so a hash made here and a hash made by any other
    SHA-256 tool over vba.rc agree.
    """
    with open(SOURCE, "rb") as handle:
        return hashlib.sha256(handle.read()).hexdigest()


def main():
    check_only = "--check" in sys.argv[1:]
    version = source_version()
    glossary = load_glossary()
    blocks = read_blocks()

    missing = {}
    output = [HEADER.replace("{version}", version)]

    for block in blocks:
        for line in block:
            if line.lstrip().startswith("//"):
                output.append(line)
                continue

            def replace(match):
                text = match.group(1)
                if text in glossary:
                    return '"%s"' % glossary[text]
                if text and text not in KEEP:
                    missing.setdefault(text, 0)
                    missing[text] += 1
                return match.group(0)

            output.append(LITERAL.sub(replace, line))
        output.append("")

    if missing:
        print("not translated (%d distinct):" % len(missing))
        for text, count in sorted(missing.items()):
            print("  %3d  %s" % (count, text))
        if check_only:
            return 1

    text = "\r\n".join(output).rstrip() + "\r\n"
    header = VERSION_HEADER_TEXT.replace("{version}", version)

    if check_only:
        try:
            with open(TARGET, encoding="utf-8-sig", newline="") as handle:
                current = handle.read()
        except FileNotFoundError:
            current = None
        if current != text:
            print("vba_chs.rc is out of date, run make_rc.py")
            return 1
        try:
            with open(VERSION_HEADER, encoding="utf-8", newline="") as handle:
                current_header = handle.read()
        except FileNotFoundError:
            current_header = None
        if current_header != header:
            print("%s is out of date, run make_rc.py"
                  % os.path.basename(VERSION_HEADER))
            return 1
        print("vba_chs.rc is up to date, %d blocks, %d strings, version %s"
              % (len(blocks), len(glossary), version))
        return 0

    with open(TARGET, "w", encoding="utf-8-sig", newline="") as handle:
        handle.write(text)
    with open(VERSION_HEADER, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(header)

    print("wrote %s and %s: %d blocks, %d strings, version %s"
          % (TARGET, VERSION_HEADER, len(blocks), len(glossary), version))
    return 0


if __name__ == "__main__":
    sys.exit(main())
